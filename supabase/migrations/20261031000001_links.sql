-- Stash schema, recovered from the live app's /api/export and from how the
-- code reads and writes it. The original DDL was never versioned.
--
-- One table, `links`: every saved tool, repo or page, enriched by an LLM,
-- searchable by keyword (fts) and by meaning (embedding, gte-small 384d).
-- The app talks to it only from the server with the service-role key, so RLS
-- is on with no policies: the anon and authenticated roles see nothing.

create extension if not exists vector with schema extensions;

-- array_to_string is not immutable, so it cannot sit in a generated column
-- directly. This wrapper is safe: joining text[] with a space never varies.
create or replace function public.immutable_join(text[])
returns text
language sql
immutable
parallel safe
set search_path = ''
as $$ select coalesce(array_to_string($1, ' '), '') $$;

create table public.links (
  id                  bigint generated by default as identity primary key,
  kind                text not null default 'link',
  url                 text not null,
  norm_url            text not null unique,
  domain              text,
  title               text,
  description         text,
  image               text,
  favicon             text,
  site_name           text,
  summary             text,
  category            text,
  pricing             text,
  is_open_source      boolean not null default false,
  use_cases           text[] not null default '{}',
  tags                text[] not null default '{}',
  collections         text[] not null default '{}',
  ocr_text            text,

  -- GitHub
  repo_owner          text,
  repo_name           text,
  repo_stars          integer,
  repo_language       text,
  repo_license        text,
  repo_pushed_at      timestamptz,
  repo_forks          integer,
  repo_open_issues    integer,
  repo_open_prs       integer,

  -- How to use it
  install             text,
  quickstart          text,
  works_with          text[] not null default '{}',
  requires            text[] not null default '{}',
  limits              text,
  avoid_when          text,
  maturity            text,
  type                text,
  role                text,
  integration_effort  text,
  commercial_ok       text,
  usage_format        text,

  -- Which part of a website it helps build
  sections            text[] not null default '{}',
  effect_kind         text[] not null default '{}',
  style_tags          text[] not null default '{}',

  -- The user's own relationship to it
  note                text,
  starred             boolean not null default false,
  used_in             text[] not null default '{}',
  used_count          integer not null default 0,
  last_used_at        timestamptz,
  why                 text,

  -- Pipeline state
  source              text,
  source_url          text,
  status              text not null default 'pending',
  error               text,
  dead                boolean not null default false,
  dead_reason         text,
  checked_at          timestamptz,
  fail_count          integer not null default 0,
  enriched_v          integer not null default 0,
  sections_v          integer not null default 0,

  embedding           extensions.vector(384),
  fts                 tsvector generated always as (
    setweight(to_tsvector('english', coalesce(title, '') || ' ' || coalesce(domain, '')), 'A') ||
    setweight(to_tsvector('english', coalesce(summary, '') || ' ' || coalesce(role, '') || ' ' ||
      coalesce(category, '') || ' ' || public.immutable_join(tags)), 'B') ||
    setweight(to_tsvector('english', coalesce(description, '') || ' ' || public.immutable_join(use_cases) || ' ' ||
      coalesce(note, '')), 'C')
  ) stored,

  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now()
);

create index links_fts_idx        on public.links using gin (fts);
create index links_embedding_idx  on public.links using hnsw (embedding extensions.vector_cosine_ops);
create index links_created_at_idx on public.links (created_at desc);
create index links_status_idx     on public.links (status);
create index links_tags_idx       on public.links using gin (tags);
create index links_sections_idx   on public.links using gin (sections);

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end $$;

create trigger links_touch before update on public.links
  for each row execute function public.touch_updated_at();

alter table public.links enable row level security;

/* ------------------------------------------------------------ search_links

   Browse (q is null): filter, then sort by sort_by.
   Search (q given):   hybrid. Keyword hits (fts, plus a plain substring
   match on title/domain for product names fts would stem away) and the 100
   nearest by meaning are merged with reciprocal-rank fusion, so a row that
   is strong on either signal surfaces, and one strong on both wins.

   Each row is the link as JSON plus total_count, so callers paginate
   without a second query. Every parameter has a default because callers
   pass different subsets.
*/
create or replace function public.search_links(
  q             text default null,
  q_embedding   extensions.vector(384) default null,
  f_category    text default null,
  f_pricing     text default null,
  f_source      text default null,
  f_kind        text default null,
  f_status      text default null,
  f_tags        text[] default null,
  f_oss         boolean default false,
  f_starred     boolean default false,
  f_collection  text default null,
  f_language    text default null,
  f_type        text default null,
  f_min_stars   integer default null,
  f_maintained  boolean default false,
  f_dead        boolean default null,     -- null: all, true: dead only, false: hide dead
  f_section     text default null,
  f_style       text default null,
  f_effect      text default null,
  f_works_with  text default null,
  f_used_only   boolean default false,
  sort_by       text default 'newest',    -- newest | oldest | stars | title
  max_rows      integer default 60,
  skip_rows     integer default 0
)
returns setof jsonb
language sql
stable
security invoker
set search_path = ''
as $$
  with filtered as (
    select l.*
    from public.links l
    where (f_category   is null or l.category = f_category)
      and (f_pricing    is null or l.pricing = f_pricing)
      and (f_source     is null or l.source = f_source)
      and (f_kind       is null or l.kind = f_kind)
      and (f_status     is null or l.status = f_status)
      and (f_tags       is null or l.tags @> f_tags)
      and (not f_oss    or l.is_open_source)
      and (not f_starred or l.starred)
      and (f_collection is null or f_collection = any (l.collections))
      and (f_language   is null or l.repo_language ilike f_language)
      and (f_type       is null or l.type = f_type)
      and (f_min_stars  is null or coalesce(l.repo_stars, 0) >= f_min_stars)
      and (not f_maintained or (
            coalesce(l.maturity, '') <> 'archived'
            and (l.repo_pushed_at is null or l.repo_pushed_at > now() - interval '1 year')))
      and (f_dead       is null or l.dead = f_dead)
      and (f_section    is null or f_section = any (l.sections))
      and (f_style      is null or f_style = any (l.style_tags))
      and (f_effect     is null or f_effect = any (l.effect_kind))
      and (f_works_with is null or exists (
            select 1 from unnest(l.works_with) w where w ilike '%' || f_works_with || '%'))
      and (not f_used_only or l.used_count > 0)
  ),
  kw as (
    select f.id,
           row_number() over (order by
             ts_rank_cd(f.fts, websearch_to_tsquery('english', q)) desc,
             (f.title ilike '%' || q || '%') desc,
             f.created_at desc) as r
    from filtered f
    where q is not null
      and (f.fts @@ websearch_to_tsquery('english', q)
           or f.title ilike '%' || q || '%'
           or f.domain ilike '%' || q || '%')
  ),
  sem as (
    select f.id,
           row_number() over (order by f.embedding operator(extensions.<=>) q_embedding) as r
    from filtered f
    where q is not null and q_embedding is not null and f.embedding is not null
    order by f.embedding operator(extensions.<=>) q_embedding
    limit 100
  ),
  hits as (
    select coalesce(kw.id, sem.id) as id,
           coalesce(1.0 / (60 + kw.r), 0) + coalesce(1.0 / (60 + sem.r), 0) as score
    from kw full join sem on sem.id = kw.id
  ),
  pool as (
    select f.*, h.score
    from filtered f
    join hits h on h.id = f.id
    where q is not null
    union all
    select f.*, null::numeric as score
    from filtered f
    where q is null
  )
  select (to_jsonb(p) - 'embedding' - 'fts' - 'score')
         || jsonb_build_object('total_count', count(*) over ())
  from pool p
  order by
    p.score desc nulls last,
    case when sort_by = 'oldest' then p.created_at end asc,
    case when sort_by = 'stars'  then coalesce(p.repo_stars, -1) end desc,
    case when sort_by = 'title'  then lower(coalesce(p.title, p.domain)) end asc,
    p.created_at desc
  limit greatest(max_rows, 0)
  offset greatest(skip_rows, 0)
$$;

/* ------------------------------------------------------------ stash_facets

   Counts for the sidebar and the MCP list_categories tool. Stages are
   derived from categories in app/api/facets, not here.
*/
create or replace function public.stash_facets()
returns jsonb
language sql
stable
security invoker
set search_path = ''
as $$
  with
  counted as (
    select 'categories' as facet, category as name from public.links where category is not null
    union all select 'collections', unnest(collections) from public.links
    union all select 'tags',        unnest(tags)        from public.links
    union all select 'sources',     source              from public.links where source is not null
    union all select 'pricing',     pricing             from public.links where pricing is not null
    union all select 'types',       type                from public.links where type is not null
    union all select 'styles',      unnest(style_tags)  from public.links
    union all select 'effects',     unnest(effect_kind) from public.links
    union all select 'sections',    unnest(sections)    from public.links
    union all select 'languages',   repo_language       from public.links where repo_language is not null
  ),
  grouped as (
    select facet, jsonb_agg(jsonb_build_object('name', name, 'count', n) order by n desc, name) as items
    from (select facet, name, count(*) as n from counted group by facet, name) x
    group by facet
  ),
  stats as (
    select jsonb_build_object(
      'total',          count(*),
      'oss',            count(*) filter (where is_open_source),
      'starred',        count(*) filter (where starred),
      'errored',        count(*) filter (where status = 'error'),
      'working',        count(*) filter (where status in ('pending', 'enriching')),
      'dead',           count(*) filter (where dead),
      'unchecked',      count(*) filter (where checked_at is null),
      'repos',          count(*) filter (where repo_owner is not null),
      'stars_total',    coalesce(sum(repo_stars), 0),
      'section_tagged', count(*) filter (where sections_v > 0)  -- processed by the tagger, even if no section fit
    ) as s
    from public.links
  )
  select coalesce((select jsonb_object_agg(facet, items) from grouped), '{}'::jsonb)
         || jsonb_build_object('stats', (select s from stats))
$$;

-- Only the server (service role) may call these.
revoke execute on function public.search_links from public, anon, authenticated;
revoke execute on function public.stash_facets from public, anon, authenticated;
revoke execute on function public.immutable_join(text[]) from anon, authenticated;
